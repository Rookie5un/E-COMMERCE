STYLE_OVERRIDES = {
    96: "Body Text",
}


def replace_paragraph_text(paragraph, text: str) -> None:
    while paragraph.runs:
        paragraph._element.remove(paragraph.runs[0]._element)
    paragraph.add_run(text.replace("`", ""))


def main() -> int:
    if not TARGET.exists():
        raise FileNotFoundError(f"Target document not found: {TARGET}")

    document = Document(str(TARGET))
    for index, text in REPLACEMENTS.items():
        replace_paragraph_text(document.paragraphs[index], text)
    for index, style_name in STYLE_OVERRIDES.items():
        document.paragraphs[index].style = document.styles[style_name]
    document.save(str(TARGET))
    print(f"[OK] updated {TARGET}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
